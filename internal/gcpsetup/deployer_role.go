// DeployerRoleID is the custom role ID used in documentation and commands.
const DeployerRoleID = "aiplexDeployer"

// DeployerRoleFile is where the generated role definition is checked in,
// relative to the repository root.
const DeployerRoleFile = "deploy/iam/aiplex-deployer-role.yaml"

// DeployerRoleYAML renders the custom role definition accepted by
// `gcloud iam roles create aiplexDeployer --project P --file FILE`.
// It holds the project-level permissions of every feature; workforce pool
// permissions are organization-level and are granted with a predefined role
// at the organization instead.
func DeployerRoleYAML() string {
	var b strings.Builder
	b.WriteString("# Generated by `aiplex platform preflight --print-role` from internal/gcpsetup.\n")
	b.WriteString("# Do not edit by hand; TestDeployerRoleFileIsCurrent fails when this file is stale.\n")
	b.WriteString("#\n")
	b.WriteString("# Create:  gcloud iam roles create " + DeployerRoleID + " --project PROJECT --file deploy/iam/aiplex-deployer-role.yaml\n")
	b.WriteString("# Update:  gcloud iam roles update " + DeployerRoleID + " --project PROJECT --file deploy/iam/aiplex-deployer-role.yaml\n")
	b.WriteString("# Grant:   gcloud projects add-iam-policy-binding PROJECT --member=user:YOU --role=projects/PROJECT/roles/" + DeployerRoleID + " --condition=None\n")
	b.WriteString("#\n")
	b.WriteString("# Not included: organization-level workforce pool permissions (feature\n")
	b.WriteString("# workforce-identity); grant roles/iam.workforcePoolAdmin on the organization\n")
	b.WriteString("# when organization_id is set.\n")
	b.WriteString("#\n")
	b.WriteString("# Not validated against a live project. Some permissions may not be supported\n")
	b.WriteString("# in custom roles; gcloud reports them when the role is created.\n")
	b.WriteString("# Permissions whose need is unverified are marked in docs/gcp-permissions.md.\n")
	b.WriteString("title: AIPlex Deployer\n")
	b.WriteString("description: Permissions aiplex platform apply needs to create and update the AIPlex Terraform. Generated from internal/gcpsetup.\n")
	b.WriteString("stage: GA\n")
	b.WriteString("includedPermissions:\n")
	for _, perm := range DeployerRolePermissions() {
		fmt.Fprintf(&b, "- %s\n", perm)
	}
	return b.String()
}

// PredefinedBindings renders, per feature, the narrowest predefined roles
// that together grant the feature's permissions, as gcloud commands for
// member. Features not in enabled are listed as comments only.
func PredefinedBindings(project, organization, member string, enabled map[FeatureID]bool) string {
	var b strings.Builder
	b.WriteString("# Predefined roles that grant what each feature needs (narrowest role per permission,\n")
	b.WriteString("# from Google's IAM role reference read 2026-11-10). Broader than the custom role.\n")
	seen := map[string]bool{}
	for _, f := range Features {
		fmt.Fprintf(&b, "\n# %s: %s (%s)\n", f.ID, f.Title, f.Toggle)
		if !enabled[f.ID] {
			b.WriteString("#   off with the current terraform.tfvars; not printed\n")
			continue
		}
		roles := FeatureRoles(f.ID)
		for _, level := range []Level{LevelProject, LevelStateBucket, LevelOrganization} {
			for _, role := range roles[level] {
				resource := "projects/" + project
				switch level {
				case LevelOrganization:
					org := organization
					if org == "" {
						org = "ORGANIZATION_ID"
					}
					resource = "organizations/" + org
				case LevelStateBucket:
					resource = "gs://" + StateBucketName(project)
				}
				key := resource + " " + role
				if seen[key] {
					fmt.Fprintf(&b, "#   %s (already listed)\n", role)
					continue
				}
				seen[key] = true
				if level == LevelStateBucket {
					b.WriteString("#   state bucket: if it does not exist yet, grant at the project instead\n")
				}
				b.WriteString(bindingCommand(resource, role, member) + "\n")
			}
		}
	}
	return b.String()
}
